CREATE TABLE public.profiles (
  id uuid NOT NULL,
  full_name text NOT NULL,
  email text NOT NULL,
  phone text NOT NULL,
  profile_picture text,
  emergency_contact_name text,
  emergency_contact_phone text,
  last_login_at timestamp with time zone,
  phone_verified boolean DEFAULT false,
  account_source text DEFAULT 'email_password'::text CHECK (account_source = ANY (ARRAY['email_password'::text, 'otp'::text, 'google'::text])),
  created_at timestamp with time zone DEFAULT now(),
  updated_at timestamp with time zone DEFAULT now(),
  national_id text,
  is_admin boolean NOT NULL DEFAULT false,
  CONSTRAINT profiles_pkey PRIMARY KEY (id),
  CONSTRAINT profiles_id_fkey FOREIGN KEY (id) REFERENCES auth.users(id)
);
CREATE TABLE public.trips (
  created_at timestamp with time zone DEFAULT now(),
  updated_at timestamp with time zone DEFAULT now(),
  driver_id uuid NOT NULL,
  route_template_id uuid,
  origin text NOT NULL,
  destination text NOT NULL,
  origin_region text,
  destination_region text,
  pickup_point text,
  dropoff_point text,
  departure_time timestamp with time zone NOT NULL,
  estimated_arrival_time timestamp with time zone,
  price_per_seat numeric NOT NULL CHECK (price_per_seat > 0::numeric),
  total_seats integer NOT NULL CHECK (total_seats > 0),
  available_seats integer NOT NULL CHECK (available_seats >= 0),
  vehicle_make text,
  vehicle_model text,
  vehicle_plate text,
  vehicle_color text,
  cancellation_reason text,
  cancelled_at timestamp with time zone,
  notes text,
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  status text NOT NULL DEFAULT 'scheduled'::text CHECK (status = ANY (ARRAY['scheduled'::text, 'ongoing'::text, 'completed'::text, 'cancelled'::text, 'expired'::text])),
  CONSTRAINT trips_pkey PRIMARY KEY (id),
  CONSTRAINT trips_driver_id_fkey FOREIGN KEY (driver_id) REFERENCES public.profiles(id),
  CONSTRAINT trips_route_template_id_fkey FOREIGN KEY (route_template_id) REFERENCES public.route_templates(id)
);
CREATE TABLE public.bookings (
  booking_reference text NOT NULL UNIQUE,
  trip_id uuid NOT NULL,
